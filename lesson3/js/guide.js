  // Сколько точек нужного цвета попало в прямоугольник [x1..x2] × [y1..y2].
  function countBox(s, label, x1, x2, y1, y2) {
    var pts = s.pts || [];
    var n = 0;
    for (var i = 0; i < pts.length; i++) {
      var p = pts[i];
      if (label && p.label !== label) continue;
      if (p.x >= x1 && p.x <= x2 && p.y >= y1 && p.y <= y2) n++;
    }
    return n;
  }

  // Есть ли точка нужного цвета возле (x, y) - в радиусе r по обеим осям.
  function hasNear(s, label, x, y, r) {
    return countBox(s, label, x - r, x + r, y - r, y + r) >= 1;
  }

  // Проверка «точки нужного цвета попали во ВСЕ перечисленные места»:
  // spots - массив [x, y]; r - допуск.
  function allSpots(label, spots, r) {
    return function (s) {
      for (var i = 0; i < spots.length; i++) {
        if (!hasNear(s, label, spots[i][0], spots[i][1], r)) return false;
      }
      return true;
    };
  }

