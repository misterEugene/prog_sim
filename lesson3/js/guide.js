  // ---------------------------------------------------------- мини-Markdown
  function escapeHtml(s) {
    return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
  }

  // Инлайн: экранируем, затем `код` и **жирный**.
  function inlineMd(s) {
    s = escapeHtml(s);
    s = s.replace(/`([^`]+)`/g, "<code>$1</code>");
    s = s.replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>");
    return s;
  }

  // Блочный парсер: заголовки #..####, списки -/*, абзацы (разделены пустой строкой).
  function mdToHtml(md) {
    var lines = md.split("\n");
    var html = "";
    var para = [];
    var list = null;

    function flushPara() {
      if (para.length) { html += "<p>" + inlineMd(para.join(" ")) + "</p>"; para = []; }
    }
    function flushList() {
      if (list) { html += "<ul>" + list.join("") + "</ul>"; list = null; }
    }

    for (var n = 0; n < lines.length; n++) {
      var t = lines[n].trim();
      if (t === "") { flushPara(); flushList(); continue; }

      var h = t.match(/^(#{1,4})\s+(.*)$/);
      if (h) {
        flushPara(); flushList();
        var lvl = h[1].length + 1; // # -> h2, ## -> h3 …
        if (lvl > 6) lvl = 6;
        html += "<h" + lvl + ">" + inlineMd(h[2]) + "</h" + lvl + ">";
        continue;
      }

      var li = t.match(/^[-*]\s+(.*)$/);
      if (li) {
        flushPara();
        if (!list) list = [];
        list.push("<li>" + inlineMd(li[1]) + "</li>");
        continue;
      }

      flushList();
      para.push(t);
    }
    flushPara(); flushList();
    return html;
  }

