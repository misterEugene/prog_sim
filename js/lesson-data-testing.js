// Пробелы/переводы строк не важны: сравниваем «схлопнутый» текст.
function t4norm(s) {
  return String(s || "").replace(/\s+/g, " ");
}

// В коде ЕСТЬ подстрока (с точностью до пробелов).
function t4has(file, sub) {
  return function (code) {
    return t4norm(code[file]).indexOf(t4norm(sub)) !== -1;
  };
}

// В коде НЕТ подстроки.
function t4hasNo(file, sub) {
  return function (code) {
    return t4norm(code[file]).indexOf(t4norm(sub)) === -1;
  };
}

// Подстрока встречается не меньше N раз (нужно, когда такая строка уже есть в
// исходном коде: например, «cartCount = 0» есть в объявлении переменной, а мы ждём
// ВТОРОГО вхождения - внутри clearCart).
function t4atLeast(file, sub, times) {
  return function (code) {
    return t4norm(code[file]).split(t4norm(sub)).length - 1 >= times;
  };
}

// Все условия сразу.
function t4all() {
  const tests = Array.prototype.slice.call(arguments);
  return function (code) {
    return tests.every(function (t) { return t(code); });
  };
}

// Вырезать из журнала багов запись BUG-NN (от её заголовка до следующей записи).
function t4bugEntry(js, num) {
  const tag = "// BUG-" + num + " |";
  const start = js.indexOf(tag);
  if (start === -1) return "";
  const rest = js.slice(start + tag.length);
  const nextAt = rest.indexOf("// BUG-");
  return nextAt === -1 ? rest.slice(0, 400) : rest.slice(0, nextAt);
}

// Запись журнала заполнена: не осталось меток [ВПИШИ …] и есть свой текст.
function t4bugFilled(num) {
  return function (code) {
    const entry = t4bugEntry(code.js, num);
    if (!entry) return false;
    if (entry.indexOf("[ВПИШИ") !== -1) return false;
    // Должен появиться осмысленный текст: хотя бы 12 «непустых» символов сверх шаблона
    const own = entry
      .replace(/\/\//g, " ")
      .replace(/Заголовок:|Шаги:|Ожидаемо:|Фактически:|Серьёзность:|Статус:/g, " ")
      .replace(/\s+/g, "");
    return own.length >= 12;
  };
}

// Во ВСЕХ 13 записях журнала не осталось меток.
function t4allBugsFilled() {
  return function (code) {
    for (let n = 1; n <= 13; n++) {
      const num = n < 10 ? "0" + n : String(n);
      if (!t4bugFilled(num)(code)) return false;
    }
    return true;
  };
}

// Статус записи BUG-NN переведён в «исправлен».
function t4bugFixed(num) {
  return function (code) {
    const entry = t4bugEntry(code.js, num).toLowerCase();
    return entry.indexOf("исправлен") !== -1;
  };
}

