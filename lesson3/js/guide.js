  // тех k, при которых тест был доведён до конца) - для шага-таблицы «точность по k».
  function hasKs(list) {
    return function (s) {
      var got = s.revealKList || [];
      for (var i = 0; i < list.length; i++) {
        if (got.indexOf(list[i]) === -1) return false;
      }
      return true;
    };
  }

